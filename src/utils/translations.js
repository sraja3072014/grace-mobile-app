export function getTranslation(language, key, variables = {}) {
  const locale = SUPPORTED_LANGUAGES.includes(language) ? language : 'en';
  const normalizedKey = keyAliases[key] || key.replace(/\./g, '_');
  const value = uiTranslations[locale][normalizedKey]
    ?? extraTranslations[locale]?.[normalizedKey]
    ?? getExistingTranslation(locale, key)
    ?? getExistingTranslation('en', key)
    ?? key;
  return String(value).replace(/\{(\w+)\}/g, (_, variable) => variables[variable] ?? `{${variable}}`);
}

